from contextlib import AbstractContextManager
from datetime import datetime
from typing import Protocol
from uuid import UUID

from app.domain.learning import (
    Attempt,
    Credential,
    LearningEvent,
    LearningSession,
    LessonVersion,
    NoteSnapshot,
    Prediction,
    TutorInteraction,
    VerificationCheck,
    VerificationRun,
)


class LearningStore(Protocol):
    def credential(self, token_hash: str) -> Credential | None: ...
    def create_identity(self, token_hash: str, expires_at: datetime) -> Credential: ...
    def revoke(self, credential_id: UUID, at: datetime) -> None: ...
    def version(self, lesson_id: str, version: str | None = None) -> LessonVersion | None: ...
    def version_by_id(self, version_id: UUID) -> LessonVersion: ...
    def publish(self, version: LessonVersion) -> None: ...
    def owned_session(self, owner: UUID, session_id: UUID) -> LearningSession | None: ...
    def session_by_key(self, owner: UUID, key: str) -> LearningSession | None: ...
    def add_session(self, session: LearningSession) -> None: ...
    def set_state(
        self, session_id: UUID, state: str, completed_at: datetime | None = None
    ) -> None: ...
    def prediction(self, session_id: UUID) -> Prediction | None: ...
    def add_prediction(self, prediction: Prediction) -> None: ...
    def attempts(self, session_id: UUID) -> list[Attempt]: ...
    def add_attempt(self, attempt: Attempt) -> None: ...
    def hints(self, session_id: UUID) -> list[TutorInteraction]: ...
    def add_hint(self, hint: TutorInteraction) -> None: ...
    def runs(self, session_id: UUID) -> list[VerificationRun]: ...
    def add_run(self, run: VerificationRun) -> None: ...
    def finish_run(self, run_id: UUID, status: str, feedback: str, at: datetime) -> None: ...
    def checks(self, run_id: UUID) -> list[VerificationCheck]: ...
    def add_check(self, check: VerificationCheck) -> None: ...
    def events(self, session_id: UUID) -> list[LearningEvent]: ...
    def add_event(self, event: LearningEvent) -> None: ...
    def add_note(self, run_id: UUID, title: str, content: str) -> NoteSnapshot: ...
    def notes(self, run_id: UUID) -> tuple[NoteSnapshot, ...]: ...


class LearningRepository(Protocol):
    def read(self) -> AbstractContextManager[LearningStore]: ...
    def write(self) -> AbstractContextManager[LearningStore]: ...
