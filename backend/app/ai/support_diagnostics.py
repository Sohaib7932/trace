"""Categorical support-stage observations; never questions, sources or identities.

Observers belong to a single request. Neither services nor the shared client retain
request state. Observation failures must never affect a delivery or safety check.
"""

import logging
from collections.abc import Callable

from app.core.middleware import SAFE_REQUEST_ID

type SupportObserver = Callable[[str, str, int | None], None]

