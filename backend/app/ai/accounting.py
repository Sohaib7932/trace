"""Trusted internal accounting/admission ports; no prompts, outputs or client identities.

Attempt and lease IDs are generated by backend code, never taken from an HTTP
request ID. Unknown/crashed work is not automatically refunded or expired.
"""

from datetime import datetime
from typing import Annotated, Literal, Protocol, Self
from uuid import UUID

from pydantic import Field, StrictInt, model_validator

from app.domain.lesson_spec.fields import Value
from app.schemas.ai_client import ClientErrorCode

type AccountingCapability = Literal["generation", "tutor", "support", "embedding"]
type Scope = Annotated[str, Field(pattern=r"^[a-zA-Z0-9][a-zA-Z0-9_.:/-]{0,95}$")]
type Digest = Annotated[str, Field(pattern=r"^[0-9a-f]{64}$")]
type Count = Annotated[StrictInt, Field(ge=0, le=1_000_000_000)]
type Positive = Annotated[StrictInt, Field(ge=1, le=100000)]
type AccountingCode = Literal[
    "duplicate", "saturated", "depleted", "unavailable", "conflict", "policy_mismatch"
]


class AIAccountingError(Exception):
    def __init__(self, code: AccountingCode) -> None:
        self.code = code
        super().__init__("AI accounting or admission is unavailable")


class AllowancePolicy(Value):
    scope: Scope
    max_attempts: Annotated[Positive, Field(le=100)] = 20
    max_in_flight: Annotated[Positive, Field(le=16)] = 4
    max_subject_in_flight: Annotated[Positive, Field(le=4)] = 1
    requests_per_minute: Annotated[Positive, Field(le=600)] = 10
    paid_budget_microusd: Literal[0] = 0

    @model_validator(mode="after")
    def consistent_limits(self) -> Self:
        if self.max_subject_in_flight > self.max_in_flight:
            raise ValueError("Subject admission cannot exceed global admission")
        return self


class ProviderAttempt(Value):
    id: UUID
    capability: AccountingCapability
    # Retain the previous model for historical reservations; new calls use GEMINI_MODEL.
    model_id: Literal["gemini-3.1-flash-lite", "gemini-3.5-flash-lite", "gemini-embedding-001"]
    subject_hash: Digest
    estimated_input_bytes: Count
    item_count: Annotated[Positive, Field(le=128)] = 1


class AttemptReservation(Value):
    attempt_id: UUID
    newly_reserved: bool
    finalized: bool


class ProviderUsage(Value):
    status: Literal["success", "refusal", "truncated", "timeout", "error"]
    error_code: ClientErrorCode | None = None
    input_tokens: Count | None = None
    output_tokens: Count | None = None
    provider_duration_ms: Count | None = None
    # Operator-attested accounting, not independently measured provider billing.
    accounted_cost_microusd: Count | None = None


class AIUsageLedger(Protocol):
    def reserve(self, policy: AllowancePolicy, attempt: ProviderAttempt) -> AttemptReservation: ...
    def finish(self, attempt_id: UUID, usage: ProviderUsage) -> None: ...


class AdmissionPolicy(Value):
    scope: Scope
    global_requests_per_minute: Annotated[Positive, Field(le=10000)]
    subject_requests_per_minute: Annotated[Positive, Field(le=1000)]
    max_global_in_flight: Annotated[Positive, Field(le=128)]
    max_subject_in_flight: Annotated[Positive, Field(le=16)]

    @model_validator(mode="after")
    def consistent_limits(self) -> Self:
        if (
            self.max_subject_in_flight > self.max_global_in_flight
            or self.subject_requests_per_minute > self.global_requests_per_minute
        ):
            raise ValueError("Subject admission cannot exceed global admission")
        return self


class AdmissionLease(Value):
    id: UUID
    admitted_at: datetime


class SharedAdmission(Protocol):
    def acquire(self, policy: AdmissionPolicy, subject_hash: Digest) -> AdmissionLease: ...
    def release(self, lease_id: UUID) -> None: ...
